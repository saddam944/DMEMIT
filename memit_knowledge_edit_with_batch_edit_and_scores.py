import matplotlib.pyplot as plt
import numpy as np

def plot_scaling_curves(all_scores_dict):
    for metric_name, values in all_scores_dict.items():
        scaling_x = []
        scaling_y = []

        total_points = len(values)
        batch_sizes = [2**i for i in range(int(np.log2(total_points)) + 1)]

        for size in batch_sizes:
            subset = values[:size]
            mean_val = np.mean(subset)
            scaling_x.append(size)
            scaling_y.append(mean_val)

        # Plot
        plt.figure(figsize=(5, 3))
        plt.plot(scaling_x, scaling_y, marker='o', color='purple')
        plt.xscale('log')
        plt.xlabel("Number of Edits (log scale)")
        plt.ylabel(metric_name)
        plt.title(f"{metric_name} ↑")
        plt.grid(True, linestyle='--', alpha=0.6)
        plt.tight_layout()
        plt.show()

plot_scaling_curves(all_scores)

