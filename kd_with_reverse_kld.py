#dataset tokenizing and then defines a custom dataset class CrisisDataset that stores the texts, their tokenized versions, and the labels
def tokenize_data(texts, tokenizer):
    return tokenizer(texts, padding=True, truncation=True, return_tensors="pt", max_length=256)

encodings = tokenize_data(texts, student_tokenizer)

class CrisisDataset(Dataset):
    def __init__(self, texts, encodings, labels):
        self.texts = texts
        self.encodings = encodings
        self.labels = labels

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        item = {key: val[idx] for key, val in self.encodings.items()}
        item["labels"] = torch.tensor(self.labels[idx])
        item["text"] = self.texts[idx]
        return item

dataset = CrisisDataset(texts, encodings, labels)
train_loader = DataLoader(dataset, batch_size=32, shuffle=True)

#AdamW optimizer for the student model with a learning rate of 2e-5, defines the distillation temperature as 1.0, and sets the training to run for 10 epochs
optimizer = AdamW(student.parameters(), lr=2e-5)
temperature = 1.0
num_epochs = 10

#calculating the Expected Calibration Error (ECE) by comparing model confidence and accuracy to assess how well probabilities reflect true correctness
def compute_ece(probs, labels, n_bins=10):
    confidences, predictions = torch.max(probs, 1)
    accuracies = predictions.eq(labels)
    ece = torch.zeros(1, device=probs.device)
    bin_boundaries = torch.linspace(0, 1, steps=n_bins + 1).to(probs.device)
    for i in range(n_bins):
        in_bin = (confidences > bin_boundaries[i]) & (confidences <= bin_boundaries[i + 1])
        prop_in_bin = in_bin.float().mean()
        if prop_in_bin.item() > 0:
            accuracy_in_bin = accuracies[in_bin].float().mean()
            avg_confidence_in_bin = confidences[in_bin].mean()
            ece += torch.abs(avg_confidence_in_bin - accuracy_in_bin) * prop_in_bin
    return ece.item()

#training the student model using reverse KL divergence with soft labels from the teacher, updating the model each step and logging average loss per epoch
step_klds = []
global_step = 0

# Training loop
for epoch in range(num_epochs):
    student.train()
    total_loss = 0
    for batch in train_loader:
        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        labels = batch["labels"].to(device)
        texts = batch["text"]

        with torch.no_grad():
            teacher_inputs = teacher_tokenizer(texts, padding=True, truncation=True, return_tensors="pt", max_length=512)
            teacher_inputs = {key: val.to(device) for key, val in teacher_inputs.items()}
            teacher_logits = teacher(**teacher_inputs).logits

        student_logits = student(input_ids, attention_mask=attention_mask).logits
        student_probs = torch.softmax(student_logits / temperature, dim=-1)
        teacher_probs = torch.softmax(teacher_logits / temperature, dim=-1)

        reverse_kld = torch.sum(student_probs * (
            torch.log(student_probs + 1e-10) - torch.log(teacher_probs + 1e-10)
        ), dim=-1).mean()

        loss = reverse_kld
        total_loss += loss.item()

        step_klds.append((global_step, reverse_kld.item()))
        global_step += 1

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

    print(f"Epoch {epoch + 1}, Avg Reverse KLD Loss: {total_loss / len(train_loader):.4f}")

#ploting the curve for training steps vs RKLD
steps, klds = zip(*step_klds)
