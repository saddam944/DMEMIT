#calculating classification loss, LM loss (for teacher/student models), accuracy, F1 score, ECE, ROUGE-L, distinct 4-grams, and average generation length for both teacher and student model
lm_model = GPT2LMHeadModel.from_pretrained(teacher_model_name).to(device)
lm_model.eval()

def evaluate(model, tokenizer, name="Model", is_teacher=False, is_student=False):
    eval_loader = DataLoader(dataset, batch_size=32, shuffle=False)
    model.eval()
    all_preds = []
    all_labels = []
    all_probs = []
    all_texts = []
    total_cls_loss = 0
    total_lm_loss = 0
    total_ngrams = set()
    total_sequences = 0
    total_gen_length = 0

    cls_loss_fn = nn.CrossEntropyLoss()
    lm_loss_fn = nn.CrossEntropyLoss(ignore_index=-100)

    with torch.no_grad():
        for batch in eval_loader:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["labels"].to(device)

            logits = model(input_ids, attention_mask=attention_mask).logits
            probs = torch.softmax(logits, dim=-1)
            preds = torch.argmax(probs, dim=-1)

            cls_loss = cls_loss_fn(logits, labels)
            total_cls_loss += cls_loss.item()

            all_preds.extend(preds.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())
            all_probs.append(probs)
            all_texts.extend(batch["text"])

            #Compute LM loss
            if is_teacher or is_student:
                lm_inputs = input_ids[:, :-1]
                lm_labels = input_ids[:, 1:].clone()
                lm_labels[attention_mask[:, 1:] == 0] = -100

                outputs = lm_model(input_ids=lm_inputs)
                lm_logits = outputs.logits
                lm_loss = lm_loss_fn(lm_logits.view(-1, lm_logits.size(-1)), lm_labels.view(-1))
                total_lm_loss += lm_loss.item()

            #Generation analysis
            decoded_texts = tokenizer.batch_decode(input_ids, skip_special_tokens=True)
            for text in decoded_texts:
                tokens = text.split()
                total_gen_length += len(tokens)
                if len(tokens) >= 4:
                    total_ngrams.update(zip(*[tokens[i:] for i in range(4)]))
                total_sequences += 1

    avg_cls_loss = total_cls_loss / len(eval_loader)
    if is_teacher or is_student:
        avg_lm_loss = total_lm_loss / len(eval_loader)
    else:
        avg_lm_loss = 0.0

    distinct_4 = len(total_ngrams) / total_sequences if total_sequences > 0 else 0.0
    avg_gen_length = total_gen_length / total_sequences if total_sequences > 0 else 0.0

    all_probs_tensor = torch.cat(all_probs, dim=0)
    all_labels_tensor = torch.tensor(all_labels).to(device)

    acc = accuracy_score(all_labels, all_preds)
    f1 = f1_score(all_labels, all_preds, average="macro")
    ece = compute_ece(all_probs_tensor, all_labels_tensor)

    scorer = rouge_scorer.RougeScorer(['rougeL'], use_stemmer=True)
    rouge_scores = []
    for t, p in zip(all_texts, all_preds):
        ref = str(p)
        rouge = scorer.score(t, ref)
        rouge_scores.append(rouge['rougeL'].fmeasure)
    rouge_avg = np.mean(rouge_scores)

    print(f"\n{name} Results:")
    print(f"Avg Classification Loss: {avg_cls_loss:.4f}")
    print(f"Avg LM Loss:             {avg_lm_loss:.4f}")
    print(f"Accuracy:                {acc:.4f}")
    print(f"F1 Score:                {f1:.4f}")
    print(f"ECE Score:               {ece:.4f}")
    print(f"ROUGE-L:                 {rouge_avg:.4f}")
    print(f"Distinct-4:              {distinct_4:.4f}")
    print(f"Avg Generation Length:   {avg_gen_length:.2f}")

    return acc, f1, ece, rouge_avg, avg_cls_loss, avg_lm_loss, distinct_4, avg_gen_length

# Evaluate both models
