import pandas as pd
import numpy as np
from transformers import pipeline, AutoModelForSequenceClassification, AutoTokenizer
from lime.lime_text import LimeTextExplainer
from sklearn.metrics import accuracy_score
from tqdm import tqdm
import torch

#using T4 gpu
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

#loading the dataset with human highlights to compare the explainablity
df = pd.read_csv("/content/Myanmar_Crisis_With_Human_Highlights.csv")
df = df.dropna(subset=["tweet_text", "class_label", "human_highlighted_tokens"])
df["class_label"] = df["class_label"].astype("category")
df["label"] = df["class_label"].cat.codes

label2id = {label: i for i, label in enumerate(df["class_label"].cat.categories)}
id2label = {i: label for label, i in label2id.items()}

#using model for explainability evaluation
model_name = "distilbert-base-uncased"
model = AutoModelForSequenceClassification.from_pretrained(model_name, num_labels=len(label2id))
tokenizer = AutoTokenizer.from_pretrained(model_name)

model = model.to(device)
classifier = pipeline("text-classification", model=model, tokenizer=tokenizer, device=0, return_all_scores=True)

#classification accuracy evaluation
def predict_label(text):
    pred = classifier(text)[0]
    return np.argmax([p['score'] for p in pred])

df["predicted_label"] = df["tweet_text"].apply(predict_label)
accuracy = accuracy_score(df["label"], df["predicted_label"])
print(f"\nAccuracy: {accuracy:.4f}")

#LIME setup
explainer = LimeTextExplainer(class_names=list(label2id.keys()))

def lime_predict(texts):
    outputs = classifier(texts)
    return np.array([[o['score'] for o in out] for out in outputs])

#Comprehensiveness & IOU metrics evaluation
sampled_df = df.copy()

comprehensiveness_scores = []
iou_scores = []

for _, row in tqdm(sampled_df.iterrows(), total=100):
    text = row["tweet_text"]
    human_highlighted = set(str(row["human_highlighted_tokens"]).split(","))

    #LIME explanation
    exp = explainer.explain_instance(text, lime_predict, num_features=10)
    lime_tokens = set([word for word, _ in exp.as_list()])

    #Comprehensiveness
    full_pred = lime_predict([text])[0]
    top_class = np.argmax(full_pred)
    original_score = full_pred[top_class]

    comp_sample = []
    for pct in [0.1, 0.3, 0.5]:
        k = max(1, int(len(lime_tokens) * pct))
        top_k_tokens = list(lime_tokens)[:k]
        modified_text = ' '.join([w for w in text.split() if w not in top_k_tokens])
        modified_score = lime_predict([modified_text])[0][top_class]
        comp_sample.append(original_score - modified_score)

    comprehensiveness_scores.append(np.mean(comp_sample))

    #IOU score
    intersection = lime_tokens & human_highlighted
    union = lime_tokens | human_highlighted
    iou = len(intersection) / len(union) if union else 0
    iou_scores.append(iou)

print(f"Accuracy: {accuracy:.4f}")
print(f"Comprehensiveness: {np.mean(comprehensiveness_scores):.4f}")
print(f"IOU: {np.mean(iou_scores):.4f}")